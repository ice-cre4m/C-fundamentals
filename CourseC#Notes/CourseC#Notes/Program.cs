//Data types in C# are used to define the type of data that a variable can hold. C# has several built-in data types

//Int - Integer data type is used to store whole numbers. It can hold values from -2,147,483,648 to 2,147,483,647. Example: int age = 25;

//Double - Double data type is used to store decimal numbers. It can hold values from approximately ±1.7 x 10^308. Example: double price = 19.99;

//String - String data type is used to store text. Example: string name = "John";

//Char - Char data type is used to store a single character. Example: char letter = 'A';

//Bool - Bool data type is used to store a boolean value (true or false). Example: bool isStudent = true;

//float - Float data type is used to store decimal numbers with less precision than double. Example: float temperature = 36.6f;

//long - Long data type is used to store whole numbers with a larger range than int. It can hold values from -9,223,372,036,854,775,808 to 9,223,372,036,854,775,807. Example: long population = 7800000000;

//uint - Unsigned integer data type is used to store whole numbers that are always positive. It can hold values from 0 to 4,294,967,295. Example: uint positiveNumber = 100;